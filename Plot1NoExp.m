function [] = Plot1NoExp(xlim, ylim, xtick, ytick, xticklabel, yticklabel, layer, xtitle, ytitle, Ph, legendlabel, legendloc, numcols)
set(gca, ...
    'Box', 'on', ...
    'Clipping', 'on', ...
    'FontSize', 20, ...
    'TickLabelInterpreter', 'latex', ...
    'XColor', 'k', ...
    'YColor', 'k', ...
    'XLim', xlim, ...
    'YLim', ylim, ...
    'XTick', xtick, ...
    'YTick', ytick, ...
    'XTickLabel', xticklabel, ...
    'YTickLabel', yticklabel, ...
    'XMinorTick', 'on', ...
    'YMinorTick', 'on', ...
    'Layer', layer, ...
    'LineWidth', 1);
axis square;
xlabel(xtitle, 'Color', zeros(1, 3), 'Visible', 'on', 'Fontsize', 27.5); xtickangle(0);
ylabel(ytitle, 'Color', zeros(1, 3), 'Visible', 'on', 'Fontsize', 27.5); ytickangle(0);
if ~isempty(legendlabel)
    legend(cat(2, Ph{1, :}), legendlabel, ...
        'AutoUpdate', 'off', ...
        'FontSize', 20, ...
        'Location', legendloc, ...
        'NumColumns', numcols);
end
end