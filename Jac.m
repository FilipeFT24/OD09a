function [JAC] = Jac(basis, mesh, intg, flag, c, C_dof, U_dof, d1Ul)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% CELL:
%--------------------------------------------------------------------------
N           = basis.N;
R           = intg.R;
NN          = N*N;
det         = mesh.det;
TNN         = mesh.TNN;
IJd         = mesh.IJd;
IJl         = mesh.IJl;
IJu         = mesh.IJu;
Jac         = mesh.Jac;
bd_         = intg.bd_;
bf_         = intg.bf_;
DDr         = intg.DDr;
DFr         = intg.DFr;
FDr         = intg.FDr;
val         = zeros(TNN, 1);
%--------------------------------------------------------------------------
d1Uc        = U_dof*bd_./det;
C           = C_dof*bf_;
%--------------------------------------------------------------------------
d1Ult       = d1Ul.';
d1Uct       = d1Uc.';
Ct          = C.';
d1Ult1      = d1Ult(:);
d1Uct1      = d1Uct(:);
Ct1         =    Ct(:);
Jacd_RK_NN  =-DFr.*d1Uct1-DDr.*Ct1+2.*c.*FDr.*d1Ult1;
Jacd_NN_K   = sum(reshape(Jacd_RK_NN.', NN, R, []), 2);
Jacd_NN_K_1 = Jacd_NN_K(:);
val(IJd, 1) = Jacd_NN_K_1;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% FACE:
%--------------------------------------------------------------------------
if flag
    %----------------------------------------------------------------------
    %----------------------------------------------------------------------
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ASSEMBLE JACOBIAN:
%--------------------------------------------------------------------------
JAC = Jac(val);
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end