function [JAC] = Jac(basis, mesh, intg, flag, c, C_dof, U_dof)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% CELL:
%--------------------------------------------------------------------------
N           = basis.N;
R           = intg.R;
NN          = N*N;
det         = mesh.det;
TNN         = mesh.TNN;
IJd         = mesh.IJd;
IJl         = mesh.IJl;
IJu         = mesh.IJu;
Jac         = mesh.Jac;
bd_         = intg.bd_;
bf_         = intg.bf_;
DDr_M       = intg.DDr_M;
DFr_M       = intg.DFr_M;
FDr_M       = intg.FDr_M;
val         = zeros(TNN, 1);
%--------------------------------------------------------------------------
d1U         = U_dof*bd_./det;
C           = C_dof*bf_;
d1Ut        = d1U.';
Ct          = C.';
d1Ut1       = d1Ut(:);
Ct1         =   Ct(:);
Jacd_RK_NN  =-(DDr_M+2.*c.*FDr_M).*d1Ut1-DFr_M.*Ct1;
Jacd_NN_K   = sum(reshape(Jacd_RK_NN.', NN, R, []), 2);
Jacd_NN_K_1 = Jacd_NN_K(:);
val(IJd, 1) = Jacd_NN_K_1;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% FACE:
%--------------------------------------------------------------------------
if flag
    %----------------------------------------------------------------------
    %----------------------------------------------------------------------
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% ASSEMBLE JACOBIAN:
%--------------------------------------------------------------------------
JAC = Jac(val);
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end