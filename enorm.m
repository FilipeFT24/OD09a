function [e_c, en2] = enorm(basis, mesh, intg, U_dof, Uh)
%--------------------------------------------------------------------------
W_    = basis.W_;
det   = mesh.det;
Xq    = intg.Xq;
bf_   = intg.bf_;
%--------------------------------------------------------------------------
Udq   = U_dof*bf_;
Uaq   = Uh(Xq);
e_q   = Udq-Uaq;
e_c   = e_q.^2*W_.*det(:, 1);
en2   = sqrt(sum(e_c, 1));
%--------------------------------------------------------------------------
end