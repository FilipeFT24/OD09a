function [Jac] = J1(basis, mesh, intg, flag, d1U)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% CELL:
%--------------------------------------------------------------------------
K    = mesh.K;
Km1  = K-1;
N    = basis.N;
det  = mesh.det;
bd   = intg.bd;
bf_  = intg.bf_;
%--------------------------------------------------------------------------
Jacl = zeros(N, N, Km1);
Jacd = zeros(N, N, K);
Jacu = zeros(N, N, Km1);
for i = 1:K
    Jacd(:, :, i) = (bf_.*d1U(i, :))*bd./det(i, 1);
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% FACE:
%--------------------------------------------------------------------------
if flag
    %----------------------------------------------------------------------
    %----------------------------------------------------------------------
end
Jac.Jacl = Jacl;
Jac.Jacd = Jacd;
Jac.Jacu = Jacu;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end