function [d1U_dof] = G1(mesh, intg, flag, U_dof, Ulb1, Urb2)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% CELL:
%--------------------------------------------------------------------------
det     = mesh.det;
dc_m    = intg.dc_m;
%--------------------------------------------------------------------------
d1U_dof = U_dof*dc_m./det;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% FACE:
%--------------------------------------------------------------------------
if flag
    %----------------------------------------------------------------------
    K                 = mesh.K;
    bfl_              = intg.bfl_;
    bfr_              = intg.bfr_;
    fl_M              = intg.fl_M;
    fr_M              = intg.fr_M;
    fl_M_i            = fl_M(1:K-1, :);
    fr_M_i            = fr_M(2:K  , :);
    fr_Mb1            = fr_M(    1, :).*2; % {v} = value
    fl_Mb2            = fl_M(    K, :).*2; % =
    %----------------------------------------------------------------------
    Ul_i              = U_dof(1:K-1, :)*bfl_;
    Ur_i              = U_dof(2:K  , :)*bfr_;
    Urb1              = U_dof(    1, :)*bfr_;
    Ulb2              = U_dof(    K, :)*bfl_;
    Ujil              = Ul_i-Ur_i; % o->
    Ujir              =-Ujil;      % <-o
    Ujb1              = Urb1-Ulb1; % <-o
    Ujb2              = Ulb2-Urb2; % o->
    rhsiL             =-fl_M_i.*Ujil;
    rhsiR             =-fr_M_i.*Ujir;
    rhsb1             =-fr_Mb1.*Ujb1;
    rhsb2             =-fl_Mb2.*Ujb2;
    d1U_dof(1:K-1, :) = d1U_dof(1:K-1, :)+rhsiL;
    d1U_dof(2:K  , :) = d1U_dof(2:K  , :)+rhsiR;
    d1U_dof(    1, :) = d1U_dof(    1, :)+rhsb1;
    d1U_dof(    K, :) = d1U_dof(    K, :)+rhsb2;
    %----------------------------------------------------------------------
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end