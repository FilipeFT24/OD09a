function [d1U_dof] = G1(mesh, intg, flag, U_dof, Ulb1, Urb2)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% CELL:
%--------------------------------------------------------------------------
det     = mesh.det;
dc_m    = intg.dc_m;
%--------------------------------------------------------------------------
d1U_dof = U_dof*dc_m./det;
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% FACE:
%--------------------------------------------------------------------------
if flag
    %----------------------------------------------------------------------
    K                 = mesh.K;
    bfl_              = intg.bfl_;
    bfr_              = intg.bfr_;
    bfl_M             = intg.bfl_M;
    bfr_M             = intg.bfr_M;
    bfl_M_i           = bfl_M(1:K-1, :);
    bfr_M_i           = bfr_M(2:K  , :);
    bfr_Mb1           = bfr_M(    1, :); 
    bfl_Mb2           = bfl_M(    K, :);
    %----------------------------------------------------------------------
    Ul_i              = U_dof(1:K-1, :)*bfl_;
    Ur_i              = U_dof(2:K  , :)*bfr_;
    Urb1              = U_dof(    1, :)*bfr_;
    Ulb2              = U_dof(    K, :)*bfl_;
    Ujil              = Ul_i-Ur_i; % o->
    Ujir              =-Ujil;      % <-o
    Ujb1              = Urb1-Ulb1; % <-o
    Ujb2              = Ulb2-Urb2; % o->
    rhsiL             = 1./2.*bfl_M_i.*Ujil;
    rhsiR             =-1./2.*bfr_M_i.*Ujir;
    rhsb1             =-bfr_Mb1.*Ujb1; % {v} = v, not v/2!
    rhsb2             = bfl_Mb2.*Ujb2; % =
    d1U_dof(1:K-1, :) = d1U_dof(1:K-1, :)-rhsiL;
    d1U_dof(2:K  , :) = d1U_dof(2:K  , :)-rhsiR;
    d1U_dof(    1, :) = d1U_dof(    1, :)-rhsb1;
    d1U_dof(    K, :) = d1U_dof(    K, :)-rhsb2;
    %----------------------------------------------------------------------
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
end